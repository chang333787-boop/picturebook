/* PICTUREBOOK-LEVELS ③: 학생 입력 → user message. 순수 함수(테스트 가능). */
exports.buildStudentStoryDraftUserMessage = function buildStudentStoryDraftUserMessage(input) {
  const level = (input && input.level === 1) ? 1 : 2;
  const storyCount = (input && (input.storyCount === 12 || input.storyCount === 15)) ? input.storyCount : 8;
  const answersText = String((input && input.answersText) == null ? '' : input.answersText).trim();
  return [
    '다음 아이의 생각 나침반 답을 바탕으로 일직선 그림책 이야기를 만들어 주세요.',
    '',
    '[아이의 생각 나침반 답 — 맥락 전용]',
    '«' + answersText + '»',
    '',
    '[조건]',
    '- 단계: ' + (level === 1
      ? '1단계 (1~2학년, 완성된 이야기)'
      : '2단계 (3~4학년, 이어쓰기 — 시작 3장면만 쓰고 멈춤·엔딩은 빈 문자열)'),
    (level === 1
      ? '- 이야기 장면 수: 정확히 ' + storyCount + '개 (엔딩은 별도)'
      : '- 이야기 장면 수: 정확히 3개 (전체 ' + storyCount + '장면 중 시작 3장면만 — 나머지 장면과 엔딩은 아이가 이어 씁니다)'),
  ].join('\n');
};
