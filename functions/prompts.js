/* ════════════════════════════════════════════════════════════════
   user message 박음 — 작품 snapshot 박은 거 박은 거 박은 박은
   ════════════════════════════════════════════════════════════════ */
exports.buildUserMessage = function (snapshot, mode) {
  /* snapshot: { sceneId: { id, title, body, isEnding, submode, choices } } */
  const scenes = Object.values(snapshot || {});
  const sceneCount = scenes.length;

  if (sceneCount === 0) {
    return '작품에 본문 박은 장면 박지 X.';
  }

  const sceneBlocks = scenes.map(s => {
    const choices = (s.choices || []).map((c, i) =>
      `  - 선택지 ${i + 1}: "${c.label}" → 다음 장면 ${c.nextId || '(없음)'}`
    ).join('\n');
    return [
      `=== 장면 ${s.id} ===`,
      `제목: ${s.title || '(없음)'}`,
      `엔딩: ${s.isEnding ? '예' : '아니오'}`,
      `모드: ${s.submode === 'imageCenter' ? '그림 중심형' : '분할형'}`,
      `본문:`,
      s.body || '(없음)',
      choices ? `선택지:\n${choices}` : '선택지: 없음',
    ].join('\n');
  }).join('\n\n');

  const intro = mode === 'check'
    ? `다음 그림책 작품을 진단해주세요. 본문 수정은 절대 하지 마세요. ${sceneCount}개 장면입니다.`
    : `다음 그림책 작품의 본문을 1단계(안심 정돈)으로 다듬어주세요. ${sceneCount}개 장면입니다.`;

  return `${intro}\n\n${sceneBlocks}`;
};
